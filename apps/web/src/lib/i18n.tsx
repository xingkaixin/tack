type Key = keyof typeof zh;
const Context = createContext({ locale: "zh", toggle: () => {}, t: (key: string) => key });
export function I18n({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState(localStorage.getItem("tack-language") || "zh");
  const toggle = () => {
    const next = locale === "zh" ? "en" : "zh";
    localStorage.setItem("tack-language", next);
    setLocale(next);
    document.documentElement.lang = next;
  };
  return (
    <Context.Provider
      value={{ locale, toggle, t: (key) => (locale === "zh" ? zh : en)[key as Key] || key }}
    >
      {children}
    </Context.Provider>
  );
}
export const useI18n = () => useContext(Context);
